export interface BSPeriod {
  period: string;
  equityCapital: number;
  reserves: number;
  borrowings: number;
  otherLiabilities: number;
  totalLiabilities: number;
  fixedAssets: number;
  cwip: number;
  investments: number;
  otherAssets: number;
  totalAssets: number;
}

export interface CompanyBS {
  symbol: string;
  periods: BSPeriod[];
}

function makePeriod(
  period: string,
  equityCapital: number,
  reserves: number,
  borrowings: number,
  otherLiabilities: number,
  fixedAssets: number,
  cwip: number,
  investments: number,
  otherAssets: number,
): BSPeriod {
  const totalLiabilities =
    equityCapital + reserves + borrowings + otherLiabilities;
  const totalAssets = fixedAssets + cwip + investments + otherAssets;
  return {
    period,
    equityCapital,
    reserves,
    borrowings,
    otherLiabilities,
    totalLiabilities,
    fixedAssets,
    cwip,
    investments,
    otherAssets,
    totalAssets,
  };
}

