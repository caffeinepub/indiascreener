export interface CFPeriod {
  period: string;
  cashFromOperating: number;
  cashFromInvesting: number;
  cashFromFinancing: number;
  netCashFlow: number;
}

export interface CompanyCF {
  symbol: string;
  periods: CFPeriod[];
}

function cf(period: string, op: number, inv: number, fin: number): CFPeriod {
  return {
    period,
    cashFromOperating: op,
    cashFromInvesting: inv,
    cashFromFinancing: fin,
    netCashFlow: op + inv + fin,
  };
}

