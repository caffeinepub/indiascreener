export const SECTORS = [...new Set(COMPANIES.map((c) => c.sector))].sort();

export function getCompany(symbol: string): Company | undefined {
  return COMPANIES.find((c) => c.symbol === symbol);
}

export function filterCompanies(params: {
  minPE?: number | null;
  maxPE?: number | null;
  minROE?: number | null;
  minROCE?: number | null;
  minMarketCap?: number | null;
  maxMarketCap?: number | null;
  minPB?: number | null;
  maxPB?: number | null;
  maxDebtEquity?: number | null;
  sector?: string | null;
}): Company[] {
  return COMPANIES.filter((c) => {
    if (params.minPE != null && c.pe < params.minPE) return false;
    if (params.maxPE != null && c.pe > params.maxPE) return false;
    if (params.minROE != null && c.roe < params.minROE) return false;
    if (params.minROCE != null && c.roce < params.minROCE) return false;
    if (params.minMarketCap != null && c.marketCap < params.minMarketCap)
      return false;
    if (params.maxMarketCap != null && c.marketCap > params.maxMarketCap)
      return false;
    if (params.minPB != null && c.pb < params.minPB) return false;
    if (params.maxPB != null && c.pb > params.maxPB) return false;
    if (params.maxDebtEquity != null && c.debtEquity > params.maxDebtEquity)
      return false;
    if (params.sector != null && c.sector !== params.sector) return false;
    return true;
  });
}
