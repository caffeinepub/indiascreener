export interface PLPeriod {
  period: string;
  sales: number;
  expenses: number;
  operatingProfit: number;
  opmPct: number;
  otherIncome: number;
  interest: number;
  depreciation: number;
  profitBeforeTax: number;
  taxPct: number;
  netProfit: number;
  eps: number;
  dividendPayoutPct: number;
}

export interface CAGRSummary {
  salesGrowth: { y5: number; y3: number; ttm: number };
  profitGrowth: { y5: number; y3: number; ttm: number };
  stockCagr: { y3: number; y1: number };
  roe: { y5: number; y3: number; lastYear: number };
}

export interface CompanyPL {
  symbol: string;
  periods: PLPeriod[];
  cagr: CAGRSummary;
}

function makePeriod(
  period: string,
  sales: number,
  expenses: number,
  otherIncome: number,
  interest: number,
  depreciation: number,
  taxPct: number,
  eps: number,
  dividendPayoutPct: number,
): PLPeriod {
  const operatingProfit = sales - expenses;
  const opmPct = Number.parseFloat(
    ((operatingProfit / sales) * 100).toFixed(1),
  );
  const profitBeforeTax =
    operatingProfit + otherIncome - interest - depreciation;
  const netProfit = Number.parseFloat(
    (profitBeforeTax * (1 - taxPct / 100)).toFixed(0),
  );
  return {
    period,
    sales,
    expenses,
    operatingProfit,
    opmPct,
    otherIncome,
    interest,
    depreciation,
    profitBeforeTax,
    taxPct,
    netProfit,
    eps,
    dividendPayoutPct,
  };
}

